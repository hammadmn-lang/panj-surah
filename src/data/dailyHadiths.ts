/**
 * Returns today's daily hadith based on the calendar date.
 * Deterministic for each calendar day, so all users see the same inspiring hadith for the day,
 * while rotating fresh every day.
 */
export function getDailyHadithForDate(date: Date = new Date()): DailyHadith {
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const index = Math.abs(dayOfYear) % DAILY_HADITHS.length;
  return DAILY_HADITHS[index];
}
